import {generateKeyPairSync} from 'node:crypto';
import {strict as assert} from 'node:assert';
import {admit,b64,clampTier,signKey,verifyKey} from '../partner.js';
import {capOf,decide} from '../embed_meter.js';
const {publicKey,privateKey}=generateKeyPairSync('ed25519');
const pub=b64(publicKey.export({type:'spki',format:'der'}).subarray(12));
const priv=b64(privateKey.export({type:'pkcs8',format:'der'}));
const origins=['http://127.0.0.1:8777'];
const all={hubs:{slug:'hubs',name:'Hubs',origins,tier:'pro',colors:{},processes:[],materials:[],quote:'/quote'}};
const now=1_700_000_000_000;
const tok=await signKey(priv,{v:1,slug:'hubs',tier:'enterprise',origins,iat:now,exp:now+864e5});
const L=await verifyKey(tok,pub,now);
assert.equal(L.slug,'hubs');
assert.equal(L.tier,'enterprise');
const ok=await admit({tok,slug:'hubs',origin:'http://127.0.0.1:8777',all,pub,now,want:'pro'});
assert.equal(ok.tier,'pro');
assert.equal(clampTier('enterprise','pro'),'pro');
await assert.rejects(()=>admit({tok,slug:'hubs',origin:'http://127.0.0.1:8797',all,pub,now}),/origin is not licensed/);
await assert.rejects(()=>admit({tok,slug:'sendcutsend',origin:origins[0],all,pub,now}),/Unknown partner/);
const bad=tok.replace(/.$/,tok.endsWith('A')?'B':'A');
await assert.rejects(()=>verifyKey(bad,pub,now),/signature is not valid/);
await assert.rejects(()=>verifyKey(tok,pub,now+864e5+1),/expired/);
assert.equal(capOf('basic'),47);
assert.equal(capOf('pro'),147);
assert.equal(capOf('enterprise'),-1);
assert.equal(decide({tier:'basic',used:46,ok:true}).allow,true);
assert.equal(decide({tier:'basic',used:47,ok:true}).allow,false);
assert.equal(decide({tier:'enterprise',used:100000,ok:true}).unlimited,true);
console.log('embed_license_test ok');
