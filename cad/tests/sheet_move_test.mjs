import {groupsOf,settleSheet,applySheetEdits,moveItem,layoutIssues} from '../drawing.js';
let bad=0;const ok=(c,m,x)=>{c||bad++;console.log((c?'PASS ':'FAIL ')+m+(x!=null?' ('+x+')':''));};
const tx=(p,txt)=>({t:'tx',p:[...p],txt,s:3,an:'s'});
const ln=(a,b)=>({t:'l',a:[...a],b:[...b],ly:'dim'});
const sh=()=>({W:200,H:140,border:[10,10,190,130],ranges:{part:[0,0],ann:[0,4]},items:[tx([20,40],'10.0'),tx([22,42],'10.0 note'),ln([18,30],[40,40]),tx([30,20],'NOTE: check edges')],views:[],keep:[[120,10,190,50]]});
const g0=groupsOf(sh());
ok(g0.some(g=>g.kind==='dim')&&g0.some(g=>g.kind==='leader'||g.kind==='note'),'groups split text and leaders',g0.map(g=>g.kind+':'+g.id).join(','));
const crowded=sh();
const before=groupsOf(crowded).filter(g=>g.box);
const overlap=before.some((g,i)=>before.some((o,j)=>j>i&&g.box&&o.box&&Math.min(g.box[2],o.box[2])>Math.max(g.box[0],o.box[0])&&Math.min(g.box[3],o.box[3])>Math.max(g.box[1],o.box[1])));
ok(overlap,'fixture starts overlapped');
const moved=settleSheet(crowded);
ok(Object.keys(moved).length>0,'settle moves something',JSON.stringify(moved));
const after=groupsOf(crowded).filter(g=>g.kind==='dim'&&g.box);
const still=after.some((g,i)=>after.some((o,j)=>j>i&&Math.min(g.box[2],o.box[2])-Math.max(g.box[0],o.box[0])>0.5&&Math.min(g.box[3],o.box[3])-Math.max(g.box[1],o.box[1])>0.5));
ok(!still,'settle separates overlapping notes');
const outside=after.some(g=>g.box[0]<9||g.box[1]<9||g.box[2]>191||g.box[3]>131);
ok(!outside,'settled notes stay inside the border');
const base=sh();
applySheetEdits(base,{place:{'dim:0':{dx:15,dy:4}},textEdit:{'dim:0':'EDITED'}});
const d0=groupsOf(base).find(g=>g.id==='dim:0');
ok(d0&&d0.text.txt==='EDITED'&&Math.abs(d0.box[0]-35)<8,'saved place and text are applied',d0&&d0.text.txt+' @'+d0.box.map(v=>v.toFixed(1)).join(','));
const q=tx([0,0],'A');moveItem(q,3,-2);ok(q.p[0]===3&&q.p[1]===-2,'nudge moves text');
ok(Array.isArray(layoutIssues({items:[],ranges:{ann:[0,0]}}))||layoutIssues({items:[]}).length===0,'layoutIssues stays safe without annotations');
console.log(bad?bad+' FAILED':'ALL PASS');
process.exit(bad?1:0);
