import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve:(s,c,n)=>s==='three'?{url:new URL('../vendor/three.module.min.js',import.meta.url).href,shortCircuit:true}:n(s,c)});
const{BONES,FACS,LANDMARKS,REGIONS,buildHuman,humanModel,landmarkOf}=await import('../human.js'),{meshEdit}=await import('../poly_agent.js'),{mergeExport}=await import('../poly_io.js'),MS=await import('../poly_store.js'),HD=await import('../headless.js');
const near=(a,b,tol=0.2)=>assert(Math.abs(a-b)<=tol,`expected ${a} near ${b} (±${tol})`);
const r0=await buildHuman({units:'in'});
assert.deepEqual(r0.mesh.validate(),[]);
assert.equal(r0.mesh.orientOK(),true);
assert.equal(r0.audit.watertight,true);
assert.equal(r0.audit.open_edges,0);
assert.equal(r0.audit.non_manifold_edges,0);
assert.equal(r0.audit.unweighted_verts,0);
assert(r0.audit.symmetry_max_mm<0.05,`symmetry ${r0.audit.symmetry_max_mm} mm`);
assert(r0.audit.ansur_rms_pct<10,`ansur rms ${r0.audit.ansur_rms_pct}%`);
assert.equal(r0.audit.bones,71);
assert.equal(BONES.length,71);
assert.equal(FACS.length,52);
assert.equal(Object.keys(r0.landmarks).length,LANDMARKS.length);
assert.equal(Object.keys(r0.regions).length,REGIONS.length);
const rM=await buildHuman({preset:'male',height_in:72,morph:{muscle:0.85,nose_length:0.5,jaw_width:0.45},units:'in'});
near(rM.audit.stature_in,72,0.2);
assert(rM.landmarks.nose_tip[1]<r0.landmarks.nose_tip[1],'nose_length projects nose_tip forward (-Y)');
assert((rM.landmarks.jaw_l[0]-rM.landmarks.jaw_r[0])>(r0.landmarks.jaw_l[0]-r0.landmarks.jaw_r[0]),'jaw_width widens jaw landmarks');
const rF=await buildHuman({preset:'female',height_in:59,expression:'smile',facs:{jawOpen:0.75,eyeBlinkLeft:1,eyeBlinkRight:1},units:'in'});
const rFN=await buildHuman({preset:'female',height_in:59,units:'in'});
assert.equal(rF.audit.watertight,true);
assert.equal(rF.audit.open_edges,0);
assert(rF.landmarks.chin[2]<rFN.landmarks.chin[2]-0.15,'jawOpen lowers chin');
assert(rF.audit.active_facs>=5,'smile + jawOpen + blink activates FACS channels');
const rP=await buildHuman({pose:{hand_l:[85,0,0],index_01_l:[0,0,-55],index_02_l:[0,0,-70],index_03_l:[0,0,-45]},units:'in'});
assert.equal(rP.audit.watertight,true);
assert(rP.audit.twist_retention_pct>90,`forearm twist retention ${rP.audit.twist_retention_pct}%`);
const rG=await buildHuman({preset:'athletic',garments:['top','pants','skirt','boots','gloves','hair_cap'],units:'in'});
assert.equal(rG.garments.length,5+1);
assert.equal(rG.audit.poke_through_verts,0,`expected 0 poke-through verts, got ${rG.audit.poke_through_verts}`);
for(const g of rG.garments){const gs=g.mesh.stats();assert.equal(gs.nonManifold,0,`garment ${g.kind} nonManifold`);assert(gs.faces>8,`garment ${g.kind} faces`);}
const doc={units:'in',form:'',meshes:{}},API={doc,S:{doc,ws:'form'},ws:'form',setWS(w){this.ws=w;this.S.ws=w;},commit(fn){fn(this.doc);},toast(){}};
const hm=await humanModel(API,{name:'hero',preset:'athletic',height_in:70,garments:['top','pants']});
assert.equal(hm.object,'hero');
assert.equal(hm.created_garments.length,2);
assert.equal(hm.audit.poke_through_verts,0);
const me1=await meshEdit(API,{object:'hero',ops:[{select:{faces:{region:'nose'}},paint_fill:{color:'#d99b82'}},{sculpt:{brush:'inflate',path:['nose_tip'],radius:0.8,strength:0.35,auto_mask:true}},{proportional_move:{center:'ear_l',d:[0.25,0,0.12],radius:1.4,falloff:'smooth',symmetry:'x'}},{human_audit:true}]});
assert.equal(me1.warnings.length,0,`me1 warnings: ${me1.warnings.join('; ')}`);
assert(me1.ops[0].selected.faces>0&&me1.ops[0].selected.faces<50,`nose region selected ${me1.ops[0].selected.faces} faces`);
const heroM=MS.mesh(doc.meshes[hm.data]),elAfter=landmarkOf(heroM,'ear_l'),erAfter=landmarkOf(heroM,'ear_r');
near(elAfter[0],-erAfter[0],0.02);
assert(elAfter[0]>hm.landmarks.ear_l[0]+0.1,'proportional_move shifted ear_l outward');
const meWrap=await meshEdit(API,{create:{kind:'cylinder',name:'band',size:14,at:[0,0,45],params:{r1:9,r2:9,d:5,segs:24}},ops:[{delete:{what:'only_f'},select:{faces:{normal:[0,0,1],within:35}}},{delete:{what:'only_f'},select:{faces:{normal:[0,0,-1],within:35}}},{shrinkwrap:{target:'hero',offset:0.12,relax:2}}]});
assert.equal(meWrap.warnings.length,0,`meWrap warnings: ${meWrap.warnings.join('; ')}`);
assert(meWrap.ops[3].moved>10,'shrinkwrap projected band vertices onto hero');
const merged=await mergeExport({pos:new Float32Array(0),nrm:new Float32Array(0),col:new Float32Array(0),idx:new Uint32Array(0),props:{nVerts:0,nTris:0}},doc,doc.form,{only:['hero','hero_top','hero_pants']});
assert(merged.skin&&merged.skin.bones.length===71,'mergeExport preserves 71-bone skin');
const glbRes=await HD.human({preset:'female',height_in:59.5,expression:'happy',pose:'relaxed',garments:['top','skirt','boots'],format:'glb'});
assert(glbRes.bytes instanceof Uint8Array&&glbRes.bytes.length>100000);
const dv=new DataView(glbRes.bytes.buffer,glbRes.bytes.byteOffset,glbRes.bytes.byteLength);
assert.equal(new TextDecoder().decode(glbRes.bytes.subarray(0,4)),'glTF');
assert.equal(dv.getUint32(4,true),2);
const jLen=dv.getUint32(12,true),gltf=JSON.parse(new TextDecoder().decode(glbRes.bytes.subarray(20,20+jLen)));
assert.equal(gltf.skins.length,1);
assert.equal(gltf.skins[0].joints.length,71);
assert(gltf.meshes[0].primitives.every(pr=>pr.attributes.JOINTS_0!=null&&pr.attributes.WEIGHTS_0!=null));
console.log('human_he_test ok:',JSON.stringify({verts:r0.mesh.nv,quads:r0.audit.quads,bones:r0.audit.bones,facs:FACS.length,landmarks:LANDMARKS.length,regions:REGIONS.length,ansur_rms_pct:r0.audit.ansur_rms_pct,twist_retention_pct:rP.audit.twist_retention_pct,garment_poke:rG.audit.poke_through_verts,glb_bytes:glbRes.bytes.length}));
