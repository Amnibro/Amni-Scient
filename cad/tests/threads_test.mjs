import {THREADS,FAMILIES,sizes,pitches,classes,callout,tapDrill,threadById,searchThreads,lookupThread} from '../threads.js';
let bad=0;const ok=(c,m,x)=>{c||bad++;console.log((c?'PASS ':'FAIL ')+m+(x!=null?' ('+x+')':''));};
const one=(id,major,pitch,unit)=>{const t=threadById(id);ok(!!t&&Math.abs(t.major-major)<1e-6&&Math.abs(t.pitch-pitch)<1e-4&&t.unit===unit,id,t&&t.major+' '+t.pitch+' '+t.unit);};
one('UNC:1/4:20',0.25,0.05,'in');
one('UNC:#10:24',0.190,1/24,'in');
one('UNF:1/4:28',0.25,1/28,'in');
one('M:M6:1',6,1,'mm');
one('MF:M10:1.25',10,1.25,'mm');
one('NPT:1/4:18',0.540,1/18,'in');
one('BSPP:1/4:'+(25.4/19).toFixed(4),13.157,+(25.4/19).toFixed(4),'mm');
ok(tapDrill(threadById('M:M6:1'))===5,'M6 tap drill is 5.00 mm',tapDrill(threadById('M:M6:1')));
ok(callout(threadById('UNC:1/2:13'),{internal:true})==='1/2-13 UNC-2B','internal UNC callout');
ok(callout(threadById('M:M8:1.25'),{cls:'6g'})==='M8x1.25-6g','metric callout');
const coarse=sizes('UNC'),fine=sizes('UNF');
ok(coarse.includes('1/4')&&!pitches('UNC','1/4').some(t=>t.tpi===28),'UNC size list does not include the UNF pitch');
ok(pitches('UNF','1/4').every(t=>t.family==='UNF')&&classes('UNF',true).join()==='2B,3B','cascade class list is internal only');
ok(searchThreads('PG16').some(t=>t.family==='PG')&&!searchThreads('PG16').some(t=>t.family==='UNC'),'search stays inside the matching family');
ok(lookupThread({std:'M6'}).pitch===1,'legacy M6 still resolves');
ok(FAMILIES.every(f=>THREADS.some(t=>t.family===f.id)),'every listed family has sizes');
console.log(bad?bad+' FAILED':'ALL PASS');
process.exit(bad?1:0);
