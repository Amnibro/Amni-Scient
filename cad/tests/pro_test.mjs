import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import * as P from '../pro.js';
let fail=0;const ok=(c,m)=>{c||fail++;console.log(c?'PASS':'FAIL',m);},rej=async(p,re,m)=>{try{await p;ok(false,m);}catch(e){ok(re.test(e.message),m+' ('+e.message+')');}};
const KEY=path.join(process.env.AMNI_SIGNING||path.join(os.homedir(),'.config/amni/signing'),'amni-cad-pro.key'),b64=b=>Buffer.from(b).toString('base64url');
const forge=(L,k)=>{const p=b64(JSON.stringify(L));return'AMNIPRO1.'+p+'.'+b64(crypto.sign(null,Buffer.from('AMNIPRO1.'+p),k));};
const other=crypto.generateKeyPairSync('ed25519').privateKey,base={v:1,id:'t1',name:'Test',org:'Acme',plan:'pro',seats:3,feat:['*'],iat:Date.now(),exp:Date.now()+864e5};
await rej(P.check('hello'),/not an Amni-CAD Pro license/,'rejects text that is not a key');
await rej(P.check(forge(base,other)),/signature is not valid/,'rejects a key signed by anyone else');
await rej(P.check('AMNIPRO1.'+b64('{"v":1}')),/incomplete/,'rejects a truncated key');
if(fs.existsSync(KEY)){const k=crypto.createPrivateKey(fs.readFileSync(KEY)),good=forge(base,k);
  const L=await P.check(good);ok(L.org==='Acme'&&L.seats===3,'accepts a key signed by the Amni-CAD Pro key');
  await rej(P.check(good.replace(/\.([^.]+)\./,(m,p)=>'.'+b64(JSON.stringify({...base,seats:999}))+'.')),/signature is not valid/,'rejects a key whose payload was edited');
  await rej(P.check(forge({...base,exp:Date.now()-1000},k)),/expired/,'rejects an expired key');
  await rej(P.check(forge({...base,v:2},k)),/newer Amni-CAD/,'rejects a future license version');
  await P.activate(forge({...base,feat:['vault']},k));ok(P.has('vault')&&!P.has('pdfstyle'),'feature-limited keys unlock only their features');
  await P.activate(good);ok(Object.keys(P.FEATURES).every(P.has),'full keys unlock every Pro feature');P.deactivate();ok(!P.active()&&!P.has('vault'),'removing the key locks Pro again');
}else console.log('SKIP signed-key checks: no signing key on this machine');
console.log(fail?'FAILURES '+fail:'ALL PASS');process.exit(fail?1:0);
