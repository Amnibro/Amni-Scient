let pass=0,fail=0;
const ok=(c,m)=>{c?pass++:(fail++,console.log('FAIL: '+m))};
const ap=(a,b,m,r)=>ok(typeof a==='number'&&isFinite(a)&&Math.abs(a-b)<=Math.abs(b)*(r||1e-9)+1e-12,m+' got '+a+' want '+b);
const Q=(Cd,d,D,dP,rho)=>{const beta=d/D,At=Math.PI*d*d/4;return Cd*At*Math.sqrt(2*dP/rho)/Math.sqrt(1-Math.pow(beta,4));};
const q1=Q(0.61,0.02625,0.0525,25000,998);
ap(q1*3600,8.688,'orifice beta.5 25kPa water -> 8.69 m3/h',1e-3);
ap(q1/(Math.PI*0.02625*0.02625/4),4.4594,'throat velocity 4.46 m/s',1e-3);
ok(Q(0.98,0.02625,0.0525,25000,998)/q1>1.6,'venturi flows ~1.6x the orifice at same dP (Cd ratio)');
ok(Q(0.61,0.02625,0.0525,100000,998)/q1-2<1e-9,'flow scales with sqrt(dP): 4x dP = 2x Q');
ok(Q(0.61,0.02625,0.0525,25000,850)>q1,'lighter fluid flows faster at same dP');
const qb9=Q(0.61,0.9*0.0525,0.0525,25000,998),qb2=Q(0.61,0.2*0.0525,0.0525,25000,998);
ok(qb9>qb2,'bigger throat more flow (sanity)');
ap(1/Math.sqrt(1-Math.pow(0.5,4)),1.0328,'velocity-of-approach factor at beta .5',1e-4);
ok((1-0.5*0.5)*25===18.75,'orifice permanent loss approx (1-beta^2)dP = 18.75 kPa');
const ratio=(Zs,Zp,fix)=>{const Zr=Zs+2*Zp;return fix==='ring'?1+Zr/Zs:fix==='sun'?1+Zs/Zr:-Zr/Zs;};
ap(ratio(24,18,'ring'),3.5,'Zs24 Zp18 ring-fixed = 3.5:1');
ap(ratio(24,18,'sun'),1.4,'sun-fixed = 1.4:1');
ap(ratio(24,18,'carrier'),-2.5,'carrier-fixed = -2.5 (reversed)');
ok(24+2*18===60,'ring teeth from meshing constraint');
ok((24+60)%3===0,'3 planets assemble (84/3)');
ok((24+60)%5!==0,'5 planets do NOT assemble (84/5)');
ap(1800/3.5,514.29,'1800 rpm in -> 514 rpm out at 3.5:1',1e-4);
const w=(Zs,Zr,ws,wc)=>(ws-wc)/( -Zr/Zs)+wc;
ap(w(24,60,1800,1800/3.5)-0,0,'Willis check: ring speed = 0 when ring fixed at computed carrier speed',1e-6);
ok(ratio(24,18,'ring')===1-(-60/24)*1,'ring-fixed identity 1+Zr/Zs from Willis');
console.log(pass+' passed, '+fail+' failed');
process.exitCode=fail?1:0;
