const E=require('../calc-engineer.js');
let pass=0,fail=0;
const ok=(c,m)=>{c?pass++:(fail++,console.log('FAIL: '+m))};
const ap=(a,b,m,r)=>ok(typeof a==='number'&&isFinite(a)&&Math.abs(a-b)<=Math.abs(b)*(r||1e-9)+1e-12,m+' got '+a+' want '+b);
const p1=E.parseVal('123.456 MPa');ok(p1&&p1.n===123.456&&p1.u==='MPa'&&p1.dim==='pressure',"parse '123.456 MPa'");ap(p1.q,5e-4,'quantum of 123.456');
const p2=E.parseVal('1.235e+7 mm⁴');ok(p2&&p2.dim==='inertia','parse exponential mm⁴');ap(p2.n,1.235e7,'exp value');ap(p2.q,0.5e4,'exp quantum');
const p3=E.parseVal('12345');ok(p3&&p3.u===null&&p3.q===0.5,'plain integer, no unit, q=0.5');
ok(E.parseVal('—')===null,'em-dash rejected');
ok(E.parseVal('FoS 2.00 OK')===null,'text-first rejected');
const p4=E.parseVal('12.3 %');ok(p4&&p4.n===12.3&&p4.dim===null,'% numeric but dimensionless');
const p5=E.parseVal('36.7 °C');ok(p5&&p5.dim==='temp','°C recognized');
const p6=E.parseVal('12.3 MPa (×1.5 transverse)');ok(p6&&p6.dim===null&&p6.n===12.3,'suffixed unit not converted but numeric');
ap(E.conv(100,'MPa','ksi'),14.5037737730209,'100 MPa -> ksi',1e-9);
ap(E.conv(25.4,'mm','in'),1,'25.4 mm -> in');
ap(E.conv(1,'kN','lbf'),224.808943099711,'1 kN -> lbf',1e-9);
ap(E.conv(100,'°C','°F'),212,'100C -> F');
ap(E.conv(300,'K','°C'),26.85,'300K -> C');
ap(E.conv(1,'m³/hr','gpm'),4.40286754,'1 m3/hr -> gpm',1e-6);
ap(E.conv(1,'in⁴','mm⁴'),416231.4256,'1 in4 -> mm4');
ap(E.conv(1,'in³','mm³'),16387.064,'1 in3 -> mm3');
ap(E.conv(10,'m','ft'),32.8083989501312,'10 m -> ft',1e-9);
for(const u in E.IMP)ok(E.TOK[u]&&E.TOK[E.IMP[u]]===E.TOK[u],'IMP map dim-consistent: '+u);
ok(E.stepUp(1500,'psi')==='ksi','psi steps up to ksi');
ok(E.stepUp(500,'psi')==='psi','small psi stays');
ok(E.stepUp(20000,'lbf')==='kip','lbf steps up to kip');
let x=0;const set=v=>{x=v};
let r=E.solveFor(set,()=>3*x+2,11,1);ok(r.ok,'linear solvable');ap(r.x,3,'linear root');
r=E.solveFor(set,()=>x*x,9,1);ok(r.ok,'quadratic solvable');ap(r.x,3,'quadratic root',1e-3);
r=E.solveFor(set,()=>5000/x,2,10);ok(r.ok,'reciprocal solvable');ap(r.x,2500,'reciprocal root',1e-3);
r=E.solveFor(set,()=>x*x+10,5,1);ok(!r.ok,'impossible target reports failure');
r=E.solveFor(set,()=>2*x,-8,-1);ok(r.ok,'negative domain solvable');ap(r.x,-4,'negative root',1e-3);
r=E.solveFor(set,()=>2*x,-8,1);ok(r.ok,'sign flip scan finds negative root from positive start');ap(r.x,-4,'flipped root',1e-2);
r=E.solveFor(set,()=>Math.round(100*(2*x+1))/100,7.4321,1,()=>0.005);ok(r.ok,'quantized output accepted within display grid');ap(r.x,3.216,'quantized root',5e-3);
r=E.solveFor(set,()=>NaN,5,1);ok(!r.ok,'all-NaN output fails cleanly');
const y0=E.solveFor(v=>{x=v},()=>x*1e6,3e6,3);ok(y0.ok&&Math.abs(y0.x-3)<1e-6,'already-at-target returns immediately');
console.log(pass+' passed, '+fail+' failed');
process.exitCode=fail?1:0;
