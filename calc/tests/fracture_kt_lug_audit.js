let pass=0,fail=0;
const ok=(c,m)=>{c?pass++:(fail++,console.log('FAIL: '+m))};
const ap=(a,b,m,r)=>ok(typeof a==='number'&&isFinite(a)&&Math.abs(a-b)<=Math.abs(b)*(r||1e-9)+1e-12,m+' got '+a+' want '+b);
const K=(Y,s,a)=>Y*s*Math.sqrt(Math.PI*a);
ap(K(1,150,0.001),8.4070,'K_I center crack 1mm @150MPa = 8.41 MPa.rt-m',1e-3);
ap(K(1.12,150,0.001),9.4158,'edge crack 12% higher',1e-3);
ap(Math.pow(100/(1*150),2)/Math.PI,0.14147,'a_c = (KIC/Ys)^2/pi = 141.5mm @150MPa KIC100',1e-4);
ok(Math.pow(100/(1*300),2)/Math.PI<Math.pow(100/(1*150),2)/Math.PI/3.9,'doubling stress quarters critical crack');
const paris=(C,m,Y,ds,a0,ac)=>{const e=1-m/2;return(Math.pow(ac,e)-Math.pow(a0,e))/(C*Math.pow(Y*ds*Math.sqrt(Math.PI),m)*e);};
ap(paris(6.9e-12,3,1,100,0.001,0.025),1.3170e6,'Paris a0 1mm to ac 25mm: 1.317M cycles',1e-3);
ap(paris(6.9e-12,3,1,100,0.001,0.002)/paris(6.9e-12,3,1,100,0.001,0.025),0.36612,'36.6% of the 1-to-25mm life is spent just going 1mm to 2mm (front-loaded)',1e-3);
ok(paris(6.9e-12,3,1,200,0.001,0.025)<paris(6.9e-12,3,1,100,0.001,0.025)/7.9,'doubling stress range cuts life by 2^3');
const kt=r=>3-3.14*r+3.667*r*r-1.527*r*r*r;
ap(kt(0),3,'infinite plate hole Kt exactly 3');
ap(kt(0.2),2.5063,'Howland d/w 0.2 -> 2.506',1e-3);
ok(kt(0.5)>2.1&&kt(0.5)<2.2,'d/w 0.5 lands at ~2.16 per Peterson chart, got '+kt(0.5).toFixed(3));
ok(kt(0.1)<kt(0)&&kt(0.3)<kt(0.1),'Kt on net section falls as hole grows');
ap(1+2*1,3,'Inglis circle (a=b) = 3 exactly matches Howland limit');
ap(1+2*3,7,'Inglis 3:1 ellipse across load = 7');
ok(1+2*0.2===1.4,'flat ellipse ALONG load relieves to 1.4');
const lug=(P,d,t,a,w)=>({sb:P/(d*t),st:P/((w-d)*t),tv:P/(2*t*(a-d/2))});
const L=lug(10000,20,15,35,70);
ap(L.sb,33.333,'bearing 10kN pin20 t15 = 33.3 MPa',1e-4);
ap(L.st,13.333,'net tension (70-20)x15 = 13.3 MPa',1e-4);
ap(L.tv,13.333,'tear-out 2x15x25 = 13.3 MPa',1e-4);
ok(L.sb<250/3&&L.st<0.577*250/3&&L.tv<0.577*250/3,'example lug passes at N=3');
const Lf=lug(100000,20,15,35,70);
ok(Lf.sb>250/3,'10x load fails bearing at N=3');
ok(lug(10000,20,15,11,70).tv>lug(10000,20,15,35,70).tv*20,'tiny edge distance explodes tear-out');
console.log(pass+' passed, '+fail+' failed');
process.exitCode=fail?1:0;
