let pass=0,fail=0;
const ok=(c,m)=>{c?pass++:(fail++,console.log('FAIL: '+m))};
const ap=(a,b,m,r)=>ok(typeof a==='number'&&isFinite(a)&&Math.abs(a-b)<=Math.abs(b)*(r||1e-9)+1e-12,m+' got '+a+' want '+b);
const C=require('../calc-cad.js');
const box=C.cube(100,50,20),mpB=C.massProps(box);
ap(mpB.volume,100000,'cube 100x50x20 volume exact',1e-9);
ap(mpB.area,16000,'cube surface area 2(5000+2000+1000)',1e-9);
ok(Math.abs(mpB.centroid.x)<1e-9&&Math.abs(mpB.centroid.y)<1e-9,'cube centroid at origin');
const moved=C.transform(box,0,0,0,10,20,30),mpM=C.massProps(moved);
ap(mpM.volume,100000,'translation preserves volume',1e-9);
ap(mpM.centroid.x,10,'centroid follows translation x',1e-6);
ap(mpM.centroid.z,30,'centroid follows translation z',1e-6);
const rot=C.transform(C.cylinder(10,10,30,64),0,0,90,0,0,0),mpR=C.massProps(rot);
const Vpoly=0.5*64*100*Math.sin(2*Math.PI/64)*30;
ap(mpR.volume,Vpoly,'rotated cylinder = inscribed-prism volume exactly',1e-6);
ok(Math.abs(mpR.volume-Math.PI*100*30)/Math.PI/100/30<0.005,'64-seg cylinder within 0.5% of pi r2 h');
const a20=C.cube(20,20,20),b20=C.transform(C.cube(20,20,20),0,0,0,10,0,0);
ap(C.massProps(C.csgUnion(a20,b20)).volume,12000,'union 20-cubes offset10 = 12000',1e-4);
ap(C.massProps(C.csgIntersect(a20,b20)).volume,4000,'intersect = 4000',1e-4);
ap(C.massProps(C.csgSubtract(a20,b20)).volume,4000,'subtract = 4000',1e-4);
const plate=C.cube(40,10,40),hole=C.cylinder(5,5,20,32);
const drilled=C.csgSubtract(plate,hole),mpD=C.massProps(drilled);
const Vhole=0.5*32*25*Math.sin(2*Math.PI/32)*10;
ap(mpD.volume,16000-Vhole,'plate minus through-hole exact vs polygon prism',1e-4);
ok(mpD.volume>15150&&mpD.volume<15250,'drilled plate ~15220 mm3, got '+mpD.volume.toFixed(1));
const off=C.csgSubtract(plate,C.transform(C.cylinder(5,5,20,32),0,0,0,10,0,0));
ok(C.massProps(off).centroid.x<-0.4,'off-center hole at +x shifts CoG to -x, got '+C.massProps(off).centroid.x.toFixed(2));
const sph=C.massProps(C.sphere(10,24,12));
ok(sph.volume>3900&&sph.volume<4189,'sphere 24x12 tessellated volume in (3900,4189), got '+sph.volume.toFixed(0));
ok(sph.volume<4*Math.PI*1000/3,'inscribed tessellation strictly under 4/3 pi r3');
const cone=C.massProps(C.cylinder(20,0,35,48));
ok(Math.abs(cone.volume-Math.PI*400*35/3)/(Math.PI*400*35/3)<0.01,'cone within 1% of pi r2 h/3, got '+cone.volume.toFixed(0));
ok(cone.centroid.y<-8&&cone.centroid.y>-9.1,'cone CoG at -h/4 = -8.75 from center, got '+cone.centroid.y.toFixed(2));
const stl=C.toSTL(drilled);
const dv=new DataView(stl);
const ntri=dv.getUint32(80,true);
ok(stl.byteLength===84+ntri*50,'binary STL byte length = 84+50n');
ok(ntri>=drilled.length,'triangle count >= polygon count (fans)');
const nx=dv.getFloat32(84,true),ny=dv.getFloat32(88,true),nz=dv.getFloat32(92,true);
ap(Math.sqrt(nx*nx+ny*ny+nz*nz),1,'first STL normal unit length',1e-4);
const chain=C.csgSubtract(C.csgUnion(C.cube(60,10,60),C.transform(C.cube(60,60,10),0,0,0,0,25,-25)),C.cylinder(5,5,30,32));
ok(C.massProps(chain).volume>0,'3-op feature chain produces positive solid');
const tor=C.torus(20,5,32,16),mpT=C.massProps(tor);
const Vpappus=2*Math.PI*Math.PI*20*25;
ok(mpT.volume>0.965*Vpappus&&mpT.volume<Vpappus,'torus R20 r5 within 3.5% under Pappus 9870, got '+mpT.volume.toFixed(0));
ok(Math.abs(mpT.centroid.x)<1e-6&&Math.abs(mpT.centroid.y)<1e-6,'torus centroid at origin');
const torHi=C.massProps(C.torus(20,5,64,32)).volume;
ok(torHi>mpT.volume&&torHi<Vpappus,'finer torus tessellation converges upward toward Pappus, got '+torHi.toFixed(0));
const rod=C.transform(C.cylinder(8,8,12,32),0,0,0,0,0,0);
const uni=C.massProps(C.csgUnion(tor,rod)).volume;
ap(uni,mpT.volume+C.massProps(rod).volume,'rod through the donut hole is disjoint: union = exact sum',1e-6);
ok(C.massProps(C.csgSubtract(C.cube(60,20,60),tor)).volume<C.massProps(C.cube(60,20,60)).volume,'torus cuts a donut groove from a block');
const bush=C.csgSubtract(C.cylinder(20,20,30,32),C.cylinder(10,10,50,32));
const cham=C.csgSubtract(bush,C.transform(C.cylinder(10,14,4,32),0,0,0,0,15,0));
const vB=C.massProps(bush).volume,vC=C.massProps(cham).volume;
ok(vC<vB,'cone-cut chamfer removes material');
ok(vB-vC>80&&vB-vC<180,'2mm/45deg bore chamfer ring removes ~134mm3 analytic (tessellated band), got '+(vB-vC).toFixed(1));
ok(C.massProps(cham).centroid.y<-0.01,'top-only chamfer shifts CoG down (sanity)');
ap(2000*100/(3*2*24),1388.889,'planetary sun-mesh Wt: 100Nm / 3 planets / m2 Zs24 = 1389 N',1e-4);
ok(2000*100/(3*2*24)<2000*100/(1*2*24)/2.9,'3 planets cut per-mesh load to a third');
console.log(pass+' passed, '+fail+' failed');
process.exitCode=fail?1:0;
